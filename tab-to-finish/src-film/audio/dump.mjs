import {bundle} from '@remotion/bundler';
import {selectComposition, openBrowser} from '@remotion/renderer';
import fs from 'fs';
import path from 'path';
const serveUrl = await bundle({entryPoint: path.resolve('src/index.ts')});
const browser = await openBrowser('chrome', {browserExecutable: '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell'});
const c = await selectComposition({serveUrl, id: 'Dump', puppeteerInstance: browser});
fs.writeFileSync('audio/timeline.json', JSON.stringify(c.props.data, null, 1));
await browser.close({silent: true});
console.log('wrote audio/timeline.json');
